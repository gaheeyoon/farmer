import assert from 'node:assert/strict';
export async function verifyGiftLinks({db,rpc,admin,anon,expectError}) {
 await db.exec('reset role; update public.farmer_inventory set available_grams=100000;');
 const u=n=>`a0000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
 const items=[{product_id:'hopungmi-5kg',quantity:1,recipient_label:'고마운 친구',message:'고마워요 <script>alert(1)</script>'},{product_id:'hopungmi-2kg',quantity:2,recipient_label:'가족',message:'건강하세요'}];
 const buy=(id=u(1),lines=items,total=46000)=>rpc('select public.farmer_buy_gifts($1,$2,$3,$4,$5,$6,$7,$8) as result',[id,'구매자','01012345678','보내는이',JSON.stringify(lines),'',total,true]);
 await anon();
 await expectError(()=>rpc('select public.farmer_admin_gift_links() as result'),'permission denied');
 await expectError(()=>db.query('select * from farmer_private.gift_links'),'permission denied');
 const receipt=await buy();assert.equal(receipt.gifts.length,2);assert.equal(receipt.total,46000);assert.deepEqual(await buy(),receipt);
 await expectError(()=>buy(u(1),[{...items[0],message:'변경'}],22000),'이미 사용');
 await expectError(()=>buy(u(2),items,1),'판매 금액');
 await expectError(()=>buy(u(3),[{...items[0],product_id:'hopungmi-5kg-pickup'}],18000),'택배');
 await expectError(()=>buy(u(4),[{...items[0],recipient_label:''}],22000),'받는 분');
 const token=receipt.gifts[0].token;assert.match(token,/^[a-f0-9]{64}$/);
 const view=t=>rpc('select public.farmer_gift_view($1) as result',[t]);
 assert.deepEqual(await view('bad'),{found:false});assert.deepEqual(await view('f'.repeat(64)),{found:false});
 assert.equal((await view(token)).state,'pending');
 const claim=(request=u(5),name='받은 사람',t=token)=>rpc('select public.farmer_claim_gift($1,$2,$3,$4,$5,$6,$7,$8) as result',[t,request,name,'010-9876-5432','04524','서울 중구 세종대로 110','101호',true]);
 await expectError(()=>claim(),'입금 확인');
 await admin();
 let list=await rpc('select public.farmer_admin_gift_links() as result');assert.equal(list.gifts.length,2);
 let order=list.gifts.find(g=>g.token===token);
 const change=(o,status,id)=>rpc('select public.farmer_admin_change_status($1,$2,$3,$4,$5,$6) as result',[o.id,status,o.version,id,'우체국택배','TEST']);
 const stock=async()=>Number((await rpc('select public.farmer_admin_summary() as result')).available_kg);
 assert.equal(await stock(),100);
 await change(order,'confirmed',u(6));assert.equal(await stock(),95);
 order={...order,version:2};
 await expectError(()=>change(order,'shipped',u(7)),'배송지');assert.equal(await stock(),95);
 assert.equal((await view(token)).state,'ready');
 const before=await rpc('select public.farmer_admin_finance_report($1,$2,$3,$4) as result',[2026,'','',0]);
 await anon();
 await expectError(()=>rpc('select public.farmer_claim_gift($1,$2,$3,$4,$5,$6,$7,$8) as result',[token,u(8),'수령인','01012345678','x','짧음','',false]),'동의');
 assert.deepEqual(await claim(),{claimed:true});assert.deepEqual(await claim(),{claimed:true});
 await expectError(()=>claim(u(9),'다른사람'),'이미 배송지');
 const privateView=await view(token);assert.equal(privateView.state,'claimed');
 for(const key of ['phone','customer_name','address','recipient_name','recipient_phone','order_id','total','token'])assert.equal(privateView[key],undefined);
 await admin();assert.equal(await stock(),95);
 const after=await rpc('select public.farmer_admin_finance_report($1,$2,$3,$4) as result',[2026,'','',0]);assert.deepEqual(after.summary,before.summary);
 order=(await rpc('select public.farmer_admin_order_list() as result')).orders.find(o=>o.id===order.id);
 assert.equal(order.is_link_gift,true);assert.equal(order.awaiting_address,false);assert.equal(order.recipient_phone,'01098765432');assert.equal(order.version,3);
 await change(order,'shipped',u(10));await change({...order,version:4},'delivered',u(11));assert.equal(await stock(),95);
 // Free gifts require an approved admin and deduct exactly once at link creation.
 const free=()=>rpc('select public.farmer_admin_create_gift_link($1,$2,$3,$4,$5,$6,$7) as result',[u(12),'hopungmi-5kg',1,'홍세환','친구','감사합니다',30]);
 await anon();await expectError(()=>free(),'permission denied');
 await db.exec("reset role;select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000002',false);set role authenticated;");await expectError(()=>free(),'관리자 권한');
 await admin();const freeLink=await free();assert.deepEqual(await free(),freeLink);assert.equal(await stock(),90);
 const freeOrder=(await rpc('select public.farmer_admin_gift_links() as result')).gifts.find(o=>o.token===freeLink.token);
 await db.exec(`reset role;update farmer_private.gift_links set expires_at=now()-interval '1 day' where order_id='${freeOrder.id}';`);
 await anon();assert.equal((await view(freeLink.token)).state,'expired');await expectError(()=>claim(u(13),'받는분',freeLink.token),'기한');
 await admin();await rpc('select public.farmer_admin_extend_gift($1,$2) as result',[freeOrder.id,30]);assert.equal((await view(freeLink.token)).state,'ready');
 await change(freeOrder,'cancelled',u(14));assert.equal(await stock(),95);assert.equal((await view(freeLink.token)).state,'cancelled');
 await anon();await expectError(()=>claim(u(15),'받는분',freeLink.token),'입금 확인');
 await admin();assert.equal((await rpc('select public.farmer_admin_gift_links() as result')).reserved_kg,0);
 console.log('PASS: paid/free gift links, canonical income, private tokens, auth, server prices, idempotent purchase/claim, no duplicate stock, shipping guard, expiry/extension/cancel and recipient privacy.');
}
